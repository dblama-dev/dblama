import { readFile } from 'node:fs/promises'
import type { Locator, Page } from '@playwright/test'
import { test, expect, runSQL, selectOption, tablePath, dbPath } from './fixtures'

const gridRows = (page: Page) => page.locator('.datagrid tbody tr').filter({ has: page.getByRole('button', { name: 'Edit', exact: true }) })
const field = (page: Page, name: string) => page.locator('.row-modal__field').filter({ has: page.locator('.row-modal__label').getByText(name, { exact: true }) })
const input = (page: Page, name: string) => field(page, name).locator('input, textarea').first()
const byId = (page: Page, id: number) => gridRows(page).filter({ has: page.getByRole('cell', { name: String(id), exact: true }) })

async function saveRow(page: Page): Promise<void> {
  await page.locator('.row-modal').getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.locator('.row-modal')).toBeHidden()
}

async function confirm(page: Page): Promise<void> {
  await page.locator('.n-popconfirm').getByRole('button', { name: /^(Confirm|OK)$/ }).click()
}

async function checkCell(row: Locator, column: number, text: string): Promise<void> {
  // Column zero is the row-selection checkbox.
  await expect(row.locator('td').nth(column)).toHaveText(text)
}

async function dump(page: Page, db: string, table: string, format: 'SQL dump' | 'CSV (comma)'): Promise<string> {
  await page.goto(dbPath(db, 'export'))
  await selectOption(page, page.getByTestId('export-format'), format)
  await page.getByRole('checkbox', { name: table, exact: true }).check()
  const downloaded = page.waitForEvent('download')
  await page.getByTestId('export-submit').click()
  const file = await downloaded
  expect(await file.failure()).toBeNull()
  const path = await file.path()
  expect(path).not.toBeNull()
  return path!
}

async function importFile(page: Page, path: string): Promise<void> {
  await page.getByTestId('import-file').setInputFiles(path)
  await page.getByTestId('import-submit').click()
  await expect(page.getByText('Import finished', { exact: true })).toBeVisible()
}

test('row CRUD preserves NULL, empty text and exact numeric values', async ({ page, db, prefix }) => {
  const table = `${prefix}_values`
  const exactId = '9007199254740993'
  const exactAmount = '12345678901234567890.123456'
  try {
    await runSQL(page, `CREATE TABLE ${table} (id INT PRIMARY KEY, note TEXT NULL, exact_id BIGINT NOT NULL, amount DECIMAL(30,6) NOT NULL)`)
    await page.goto(tablePath(db, table))
    await page.getByRole('button', { name: 'Add row', exact: true }).click()
    await input(page, 'id').fill('1')
    await input(page, 'exact_id').fill(exactId)
    await input(page, 'amount').fill(exactAmount)
    await field(page, 'note').getByRole('checkbox', { name: 'NULL', exact: true }).check()
    await expect(input(page, 'note')).toBeDisabled()
    await saveRow(page)
    await expect(gridRows(page)).toHaveCount(1)
    await checkCell(byId(page, 1), 2, 'NULL')
    await checkCell(byId(page, 1), 3, exactId)
    await checkCell(byId(page, 1), 4, exactAmount)

    await byId(page, 1).getByRole('button', { name: 'Edit', exact: true }).click()
    await expect(input(page, 'exact_id')).toHaveValue(exactId)
    await expect(input(page, 'amount')).toHaveValue(exactAmount)
    await field(page, 'note').getByRole('checkbox', { name: 'NULL', exact: true }).uncheck()
    await input(page, 'note').fill('')
    await saveRow(page)
    await checkCell(byId(page, 1), 2, '')
    await expect(byId(page, 1).locator('.datagrid__null')).toHaveCount(0)
    await checkCell(byId(page, 1), 3, exactId)
    await checkCell(byId(page, 1), 4, exactAmount)

    await byId(page, 1).getByRole('button', { name: 'Edit', exact: true }).click()
    await input(page, 'note').fill('Клиент says "hello", O\'Brien; 第二行\nnext line')
    await saveRow(page)
    await expect(byId(page, 1)).toContainText('Клиент says "hello", O\'Brien; 第二行')
    await page.reload()
    await checkCell(byId(page, 1), 3, exactId)
    await checkCell(byId(page, 1), 4, exactAmount)
    await byId(page, 1).getByRole('button', { name: 'Delete', exact: true }).click()
    await expect(gridRows(page)).toHaveCount(0)
  } finally {
    await runSQL(page, `DROP TABLE IF EXISTS ${table}`)
  }
})

test('copy rows generates new IDs and bulk upsert updates a conflict', async ({ page, db, engine, prefix }) => {
  const table = `${prefix}_copies`
  const identity = engine === 'postgres' ? 'INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INT AUTO_INCREMENT PRIMARY KEY'
  try {
    await runSQL(page, `CREATE TABLE ${table} (id ${identity}, name VARCHAR(100) NOT NULL, note TEXT NULL); INSERT INTO ${table} (name, note) VALUES ('original', NULL)`)
    await page.goto(tablePath(db, table))
    await byId(page, 1).getByTestId('copy-row').click()
    await expect(input(page, 'id')).toHaveValue('')
    await expect(input(page, 'name')).toHaveValue('original')
    await input(page, 'name').fill('single copy')
    await saveRow(page)
    await expect(gridRows(page)).toHaveCount(2)
    await checkCell(byId(page, 2), 2, 'single copy')
    await checkCell(byId(page, 2), 3, 'NULL')

    await byId(page, 2).getByRole('checkbox').check()
    await page.getByRole('button', { name: 'Copy selected (1)', exact: true }).click()
    await confirm(page)
    await expect(gridRows(page)).toHaveCount(3)
    await checkCell(byId(page, 3), 2, 'single copy')

    await page.getByRole('button', { name: 'Insert or update JSON', exact: true }).click()
    await page.locator('form textarea').fill(JSON.stringify([
      { id: 1, name: 'updated', note: '' },
      { id: 20, name: 'new from JSON', note: null },
    ]))
    await page.locator('form').getByRole('button', { name: 'Save', exact: true }).click()
    await confirm(page)
    await expect(gridRows(page)).toHaveCount(4)
    await checkCell(byId(page, 1), 2, 'updated')
    await checkCell(byId(page, 1), 3, '')
    await checkCell(byId(page, 20), 3, 'NULL')
    await byId(page, 2).getByRole('checkbox').check()
    await byId(page, 3).getByRole('checkbox').check()
    await page.getByRole('button', { name: 'Delete selected (2)', exact: true }).click()
    await confirm(page)
    await expect(gridRows(page)).toHaveCount(2)
    await expect(byId(page, 1)).toBeVisible()
    await expect(byId(page, 20)).toBeVisible()
  } finally {
    await runSQL(page, `DROP TABLE IF EXISTS ${table}`)
  }
})

test('filters, sorting and page deletion keep results and exported selection consistent', async ({ page, db, prefix }) => {
  const table = `${prefix}_pages`
  const values = Array.from({ length: 26 }, (_, i) => `(${i + 1}, ${i % 2 ? 'NULL' : "'odd'"})`).join(',')
  try {
    await runSQL(page, `CREATE TABLE ${table} (id INT PRIMARY KEY, tag VARCHAR(20) NULL); INSERT INTO ${table} VALUES ${values}`)
    await page.goto(tablePath(db, table))
    await expect(gridRows(page)).toHaveCount(26)
    await selectOption(page, page.locator('.datagrid__filter-column'), 'tag')
    await selectOption(page, page.locator('.datagrid__filter-op'), 'IS NULL')
    await expect(page.locator('.datagrid__filter-value input')).toBeDisabled()
    await page.getByRole('button', { name: 'Apply', exact: true }).click()
    await expect(gridRows(page)).toHaveCount(13)
    await page.locator('.datagrid__filters').getByRole('button', { name: '+', exact: true }).click()
    await selectOption(page, page.locator('.datagrid__filter-column').nth(1), 'id')
    await selectOption(page, page.locator('.datagrid__filter-op').nth(1), '>=')
    await page.locator('.datagrid__filter-value input').nth(1).fill('20')
    await page.getByRole('button', { name: 'Apply', exact: true }).click()
    await expect(gridRows(page)).toHaveCount(4)
    await page.getByRole('columnheader', { name: 'id', exact: true }).click()
    await checkCell(gridRows(page).first(), 1, '26')
    await page.getByRole('columnheader', { name: 'id', exact: true }).click()
    await checkCell(gridRows(page).first(), 1, '20')
    const downloaded = page.waitForEvent('download')
    await page.getByTestId('grid-export').click()
    const file = await downloaded
    expect(await file.failure()).toBeNull()
    const csv = await readFile((await file.path())!, 'utf8')
    expect(csv.trim().split(/\r?\n/).slice(1).map(line => line.split(',')[0])).toEqual(['20', '22', '24', '26'])

    await page.getByRole('button', { name: 'Reset', exact: true }).click()
    await expect(gridRows(page)).toHaveCount(26)
    await selectOption(page, page.locator('.n-pagination .n-select'), '25 / page')
    await expect(gridRows(page)).toHaveCount(25)
    await page.locator('.n-pagination-item').filter({ hasText: /^2$/ }).click()
    await expect(gridRows(page)).toHaveCount(1)
    await gridRows(page).first().getByRole('button', { name: 'Delete', exact: true }).click()
    await expect(gridRows(page)).toHaveCount(25)
    await expect(page.locator('.n-pagination-item--active')).toHaveText('1')
  } finally {
    await runSQL(page, `DROP TABLE IF EXISTS ${table}`)
  }
})

test('SQL console handles multiple statements, errors, selection and explain', async ({ page, engine, prefix }) => {
  const table = `${prefix}_console`
  try {
    await runSQL(page, `CREATE TABLE ${table} (id INT PRIMARY KEY, note VARCHAR(100)); INSERT INTO ${table} VALUES (1, 'semi;colon'), (2, 'second'); SELECT note FROM ${table} ORDER BY id; SELECT COUNT(*) AS total FROM ${table}`)
    await expect(page.locator('.resultgrid')).toHaveCount(4)
    await expect(page.locator('.resultgrid').nth(1)).toContainText('2 rows affected')
    await expect(page.locator('.resultgrid').nth(2).locator('tbody tr')).toHaveText(['semi;colon', 'second'])
    await expect(page.locator('.resultgrid').nth(3).locator('tbody td')).toHaveText('2')
    const editor = page.locator('.cm-content')
    await editor.fill(`SELECT missing_column FROM ${table}`)
    await page.getByRole('button', { name: 'Execute all', exact: true }).click()
    await expect(page.locator('.console__error')).toBeVisible()
    await expect(page.locator('.resultgrid')).toHaveCount(0)

    await editor.fill(`SELECT note FROM ${table} WHERE id = 1;\nSELECT missing_column FROM ${table};`)
    await editor.press('Control+Home')
    await editor.press('Shift+End')
    await page.getByRole('button', { name: 'Execute selection', exact: true }).click()
    await expect(page.locator('.resultgrid')).toHaveCount(1)
    await expect(page.locator('.resultgrid tbody td')).toHaveText('semi;colon')
    await expect(page.locator('.console__error')).toBeHidden()
    await editor.fill(`SELECT * FROM ${table} WHERE id = 1`)
    await page.getByRole('button', { name: 'EXPLAIN', exact: true }).click()
    await expect(page.locator('.resultgrid th').filter({ hasText: engine === 'postgres' ? 'QUERY PLAN' : 'select_type' })).toBeVisible()
    await expect(page.locator('.resultgrid tbody tr').first()).toBeVisible()
    await expect(page.locator('.console__error')).toBeHidden()
  } finally {
    await runSQL(page, `DROP TABLE IF EXISTS ${table}`)
  }
})

test('SQL export and import restore schema, NULL, empty text and exact numbers', async ({ page, db, prefix }) => {
  const table = `${prefix}_sql_dump`
  try {
    await runSQL(page, `CREATE TABLE ${table} (id INT PRIMARY KEY, note TEXT NULL, amount DECIMAL(30,6) NOT NULL); INSERT INTO ${table} VALUES (1, NULL, 12345678901234567890.123456), (2, '', 0.000001), (3, 'O''Brien; Юникод', -99.123456)`)
    const path = await dump(page, db, table, 'SQL dump')
    const sql = await readFile(path, 'utf8')
    expect(sql).toContain(table)
    expect(sql).toContain('12345678901234567890.123456')
    await runSQL(page, `DROP TABLE ${table}`)
    await page.goto(dbPath(db, 'import'))
    await importFile(page, path)
    await page.goto(tablePath(db, table))
    await expect(gridRows(page)).toHaveCount(3)
    await checkCell(byId(page, 1), 2, 'NULL')
    await checkCell(byId(page, 1), 3, '12345678901234567890.123456')
    await checkCell(byId(page, 2), 2, '')
    await checkCell(byId(page, 2), 3, '0.000001')
    await checkCell(byId(page, 3), 2, "O'Brien; Юникод")
    await byId(page, 3).getByRole('button', { name: 'Edit', exact: true }).click()
    await input(page, 'note').fill('editable after restore')
    await saveRow(page)
    await checkCell(byId(page, 3), 2, 'editable after restore')
  } finally {
    await runSQL(page, `DROP TABLE IF EXISTS ${table}`)
  }
})

test('CSV export and import roundtrip commas, quotes, Unicode and multiline text', async ({ page, db, prefix }) => {
  const table = `${prefix}_csv_dump`
  const note = 'comma, "quoted" Юникод\nsecond line'
  try {
    // MySQL CSV import intentionally treats empty fields as NULL. Use SQL
    // dumps (covered above) when the distinction from empty text matters.
    await runSQL(page, `CREATE TABLE ${table} (id INT PRIMARY KEY, note TEXT NOT NULL); INSERT INTO ${table} VALUES (1, '${note}'), (2, 'second record')`)
    const path = await dump(page, db, table, 'CSV (comma)')
    const csv = await readFile(path, 'utf8')
    expect(csv).toContain('""quoted""')
    expect(csv).toContain('Юникод')
    await runSQL(page, `DELETE FROM ${table}`)
    await page.goto(dbPath(db, 'import'))
    await page.locator('.n-radio').filter({ has: page.locator('input[value="csv"]') }).click()
    await selectOption(page, page.getByTestId('import-table'), table)
    await page.getByRole('checkbox', { name: 'Skip the header row', exact: true }).check()
    await importFile(page, path)
    await page.goto(tablePath(db, table))
    await expect(gridRows(page)).toHaveCount(2)
    await checkCell(byId(page, 1), 2, note)
    await checkCell(byId(page, 2), 2, 'second record')
  } finally {
    await runSQL(page, `DROP TABLE IF EXISTS ${table}`)
  }
})
